#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
iikae_bench.py -- 「覚えた問題しか解けないのか」を測る

  bench.py は、同じ33問を3回まわして 97% 当たる。
  だがそれは「覚えたものが引けている」だけかもしれない。

  ここでは bench.py に **一度も出てこない言い方** だけを並べる。
  中身は同じことを頼んでいる。言い方だけが違う。

  これが低ければ「覚えた問題しか解けない」が本当。
  高ければ、言い換えには元から強い、ということになる。
"""
import io, os, sys, time, contextlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kernel

# (言い方, 答えに入っているはずの文字列, 元の言い方)
CASES = [
    # 数える（画像が5個）
    ("デスクトップの写真、何枚ある",            "5 個", "デスクトップの写真を数えて"),
    ("机の上の画像の枚数を教えて",              "5 個", "同上"),
    ("デスクトップに画像いくつ置いてある？",     "5 個", "同上"),
    ("Desktopの写真の数は",                     "5 個", "同上"),
    ("デスクトップにある絵は何個",              "5 個", "同上"),
    # 動画（1個）
    ("デスクトップにムービーいくつある",         "1 個", "デスクトップの動画は何個？"),
    ("机の上の映像ファイルの数",                "1 個", "同上"),
    # PDF（1個）
    ("デスクトップのPDFファイルは何枚",         "1 個", "デスクトップのPDFを数えて"),
    ("Desktop の pdf の個数を",                 "1 個", "同上"),
    # 一覧
    ("デスクトップの中身を全部言って",          "旅行1.jpg", "デスクトップには何がある？"),
    ("机の上に置いてあるものを教えて",          "旅行1.jpg", "同上"),
    ("Desktopのファイル名をずらっと出して",     "旅行1.jpg", "同上"),
    # ダウンロード
    ("ダウンロードフォルダのPDFの数",           "3 個", "ダウンロードのPDFを数えて"),
    ("落としたPDFって何個ある",                 "3 個", "同上"),
    ("Downloads の中身を見せて",                "請求書.pdf", "ダウンロードには何がある？"),
    # 時期つき
    ("去年デスクトップに置いた写真の数",         "4 個", "デスクトップの去年の写真を数えて"),
    ("机の上の1年前の画像は何枚",               "4 個", "同上"),
    # 書類
    ("デスクトップの資料は何個",                "2 個", "デスクトップの書類を数えて"),
    ("机の上のドキュメントの数を",              "2 個", "同上"),
    # テキスト
    ("デスクトップのメモ書きの数",              "1 個", "デスクトップのテキストを数えて"),
    # 0件
    ("デスクトップに音声ファイルいくつ",         "0 個", "デスクトップの音楽を数えて"),
    # 整理・移動
    ("机の上の画像をひとまとめにして",          "個を",  "デスクトップの写真を集めて"),
    ("デスクトップの写真をフォルダに入れといて", "個を",  "同上"),
    # 一番
    ("デスクトップでいちばん重いファイルは",     "mp4",   "一番大きいファイル"),
    ("机の上で最も古いのはどれ",                "-",     "一番古いファイル"),
]


def once(text):
    kernel.make_demo()
    buf = io.StringIO()
    t0 = time.time()
    try:
        with contextlib.redirect_stdout(buf):
            ans = kernel.handle(text)
    except Exception as e:
        ans = f"（落ちた: {e}）"
    return (ans or ""), (time.time() - t0) * 1000


def main():
    ok = 0
    warui = []
    for text, want, moto in CASES:
        ans, ms = once(text)
        good = want in ans
        ok += good
        print(f"  {'✓' if good else '✗'} {text}")
        if not good:
            warui.append((text, want, ans.replace("\n", " ")[:70], moto))
    n = len(CASES)
    print(f"\n■ 見たことのない言い方 {n} 問")
    print(f"  正解: {ok}/{n} （{ok/n*100:.0f}%）")
    if warui:
        print("\n■ 外したもの")
        for text, want, ans, moto in warui:
            print(f"  ・{text}")
            print(f"      ほしい「{want}」／ 出た「{ans}」")
            print(f"      元の言い方: {moto}")


if __name__ == "__main__":
    main()
