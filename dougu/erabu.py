_DOUGU_GYOU = re.compile(r"^\s*道具\s*[:：]\s*(.+?)\s*$", re.M)


def oshie() -> str:
    return OSHIE % ichiran()


def yomu(text: str):
    """頭脳の返事から「道具: 言い方」を取り出し、machine.match に通す。無ければ None、当たらなければ ("", 言い方)"""
    m = _DOUGU_GYOU.search(text or "")
    if not m:
        return None
    iikata = m.group(1).strip().strip("「」『』\"'")
    import machine
    hit = machine.match(iikata)
    if hit:
        return hit
    # 頭脳が「道具: 計算: 1234×56は？」と用件名を頭に付けることがある（実測 2/24）。用件名を外してもう一度
    m2 = re.match(r"^\s*([^:：\s]{1,14})\s*[:：]\s*(.+)$", iikata)
    if m2 and m2.group(1) in machine.OPS:
        na, nokori = m2.group(1), m2.group(2).strip()
        hit = machine.match(nokori)
        if hit:
            return hit
        # 言い方が決まった形でなくても、用件名が合っていて材料が取れるなら通す（語＝「」の中）
        slots = {"_文": nokori}
        q = machine._quoted(nokori) or nokori.strip("「」『』")
        if na in ("ファイルを探す", "メモを探す", "辞書", "ショートカットを実行", "ネットで調べる", "ウィキペディア"):
            slots["語"] = q
        elif na in ("メモを書く", "リマインダーに入れる", "読み上げる", "知らせる"):
            slots["文"] = q
        elif na in ("メールを送る", "メッセージを送る", "計算", "アプリをひらく", "音量をかえる"):
            return ("", iikata)      # 材料の形が要るものは 決まった言い方でないと動かさない
        return (na, slots)
    return ("", iikata)
